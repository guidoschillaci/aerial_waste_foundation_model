"""
AerialWaste PyTorch Dataset.

Supports:
  - Binary classification (waste / no waste)
  - Multi-label waste type classification (15 classes)
  - Instance segmentation via COCO masks
  - Per-source filtering (agea / wv3 / ge)
"""

import json
from pathlib import Path
from typing import Callable, Optional

import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset
from torchvision import transforms as T


class AerialWasteDataset(Dataset):
    """
    AerialWaste dataset wrapper.

    Args:
        manifest_path: Path to split manifest JSON (generated by prepare_dataset.py)
        images_dir:    Directory containing processed images for this split
        task:          "classification" | "multilabel" | "segmentation"
        source_filter: None = all sources, or one of "agea", "wv3", "ge"
        transform:     Optional image transform (torchvision or albumentations)
        norm_stats:    Dict with "mean" and "std" lists for normalization
        image_size:    Resize target (H, W)
    """

    WASTE_TYPES = [
        "rubble_excavated_earth", "bulky_items", "firewood", "scrap", "plastic",
        "vehicles", "tires", "domestic_appliances", "paper",
        "sludge_zootechnical_manure", "stone_marble_waste", "asphalt_milling",
        "corrugated_sheets_asbestos", "glass", "foundry_waste",
    ]

    STORAGE_MODES = [
        "heaps_not_delimited", "container", "big_bags", "pallets",
        "delimited_heaps", "cisterns", "drums_bins",
    ]

    DEFAULT_MEAN = [0.485, 0.456, 0.406]  # ImageNet fallback
    DEFAULT_STD  = [0.229, 0.224, 0.225]

    def __init__(
        self,
        manifest_path: str | Path,
        images_dir: str | Path,
        task: str = "classification",
        source_filter: Optional[str] = None,
        transform: Optional[Callable] = None,
        norm_stats: Optional[dict] = None,
        image_size: tuple[int, int] = (224, 224),
    ):
        self.images_dir = Path(images_dir)
        self.task = task
        self.image_size = image_size

        mean = norm_stats["mean"] if norm_stats else self.DEFAULT_MEAN
        std  = norm_stats["std"]  if norm_stats else self.DEFAULT_STD

        self.normalize = T.Normalize(mean=mean, std=std)
        self.to_tensor = T.ToTensor()
        self.resize    = T.Resize(image_size, antialias=True)
        self.transform = transform

        # Load manifest
        with open(manifest_path) as f:
            manifest = json.load(f)

        # Filter by source if requested
        if source_filter is not None:
            manifest = [m for m in manifest if m.get("source") == source_filter]

        # Filter to items with masks for segmentation task
        if task == "segmentation":
            manifest = [m for m in manifest if m.get("has_mask", False)]

        self.manifest = manifest
        self._log_stats()

    def _log_stats(self):
        n = len(self.manifest)
        if n == 0:
            print("  Dataset: 0 items")
            return
        pos = sum(m["label"] for m in self.manifest)
        print(f"  Dataset: {n} items | {pos} positive ({100*pos/n:.1f}%) | "
              f"{n-pos} negative ({100*(n-pos)/n:.1f}%)")

    def __len__(self) -> int:
        return len(self.manifest)

    def __getitem__(self, idx: int) -> dict:
        item = self.manifest[idx]

        # ── Load image ───────────────────────────────────────────────────────
        img_path = self.images_dir / item["file"]
        img = Image.open(img_path).convert("RGB")

        if self.transform is not None:
            img = self.transform(img)
        else:
            img = self.resize(img)
            img = self.to_tensor(img)
            img = self.normalize(img)

        # ── Build label ──────────────────────────────────────────────────────
        if self.task == "classification":
            label = torch.tensor(item["label"], dtype=torch.long)
        elif self.task == "multilabel":
            label = torch.tensor(item["waste_types"], dtype=torch.float32)
        elif self.task == "segmentation":
            # Return binary label; masks loaded separately during SAM 3 inference
            label = torch.tensor(item["label"], dtype=torch.long)
        else:
            raise ValueError(f"Unknown task: {self.task}")

        return {
            "image": img,
            "label": label,
            "id": item["id"],
            "source": item["source"],
            "file": item["file"],
            "evidence": item.get("evidence", -1),
            "severity": item.get("severity", -1),
        }

    @property
    def class_weights(self) -> torch.Tensor:
        """Compute inverse-frequency class weights for imbalanced training."""
        n = len(self.manifest)
        n_pos = max(sum(m["label"] for m in self.manifest), 1)
        n_neg = n - n_pos
        weight_neg = n / (2.0 * n_neg)
        weight_pos = n / (2.0 * n_pos)
        return torch.tensor([weight_neg, weight_pos], dtype=torch.float32)

    @staticmethod
    def collate_fn(batch: list[dict]) -> dict:
        return {
            "image":    torch.stack([b["image"] for b in batch]),
            "label":    torch.stack([b["label"] for b in batch]),
            "id":       [b["id"] for b in batch],
            "source":   [b["source"] for b in batch],
            "file":     [b["file"] for b in batch],
            "evidence": [b["evidence"] for b in batch],
            "severity": [b["severity"] for b in batch],
        }
